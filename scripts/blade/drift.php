<?php

declare(strict_types=1);

/*
 * Blade compiler drift check.
 *
 * Lists the directive `compile*` methods of Illuminate\View\Compilers\BladeCompiler (via reflection,
 * so trait methods are included), lowercases them and diffs the result against
 * known-compile-methods.txt. Any added/removed method means Laravel changed its directive
 * inventory and markup_fmt's directive table (markup_fmt/src/blade.rs) needs a manual review.
 *
 * Usage:
 *   php drift.php [--autoload=/path/to/vendor/autoload.php] [--known=known-compile-methods.txt] [--print]
 *
 *   --print   print the current inventory in known-compile-methods.txt format (header included) and exit 0
 *
 * Exit status: 0 no drift, 1 drift, 2 usage/environment error.
 */

// Methods named compile* that are compiler plumbing, not `@directive` handlers (lowercased).
const HELPERS = [
    'compile',                      // compile a file to cache
    'compilestring',                // entry point
    'compilecomponenttags',         // <x-…> tag pre-pass
    'compileextensions',            // Blade::extend() pipeline
    'compilestatements',            // directive regex driver
    'compilestatement',             // per-directive dispatcher
    'compileechos',                 // {{ }} family driver
    'compileregularechos',          // {{ }} handler
    'compilerawechos',              // {!! !!} handler
    'compileescapedechos',          // {{{ }}} handler
    'compilecomments',              // {{-- --}} handler
    'compileclasscomponentopening', // emitted by the <x-…> pre-pass
    'compileendcomponentclass',     // emitted by the <x-…> pre-pass
];

$autoload = __DIR__.'/vendor/autoload.php';
$known = __DIR__.'/known-compile-methods.txt';
$print = false;

foreach (array_slice($argv, 1) as $arg) {
    if (str_starts_with($arg, '--autoload=')) {
        $autoload = substr($arg, strlen('--autoload='));
    } elseif (str_starts_with($arg, '--known=')) {
        $known = substr($arg, strlen('--known='));
    } elseif ($arg === '--print') {
        $print = true;
    } else {
        fwrite(STDERR, "unknown argument: {$arg}\n");
        exit(2);
    }
}

if (! is_file($autoload)) {
    fwrite(STDERR, "autoload not found: {$autoload} (run `composer install` in scripts/blade or pass --autoload=)\n");
    exit(2);
}

require $autoload;

$current = [];
foreach ((new ReflectionClass(Illuminate\View\Compilers\BladeCompiler::class))->getMethods() as $method) {
    $name = strtolower($method->getName());
    if (str_starts_with($name, 'compile') && ! in_array($name, HELPERS, true)) {
        $current[$name] = true;
    }
}
$current = array_keys($current);
sort($current);

$version = 'unknown';
foreach (['laravel/framework', 'illuminate/view'] as $package) {
    if (class_exists(Composer\InstalledVersions::class) && Composer\InstalledVersions::isInstalled($package)) {
        $version = Composer\InstalledVersions::getPrettyVersion($package) ?? 'unknown';
        break;
    }
}

if ($print) {
    echo "# Laravel {$version}\n";
    echo "# Directive compile* methods of BladeCompiler (lowercased). Generated by: php drift.php --print\n";
    echo implode("\n", $current), "\n";
    exit(0);
}

if (! is_file($known)) {
    fwrite(STDERR, "known list not found: {$known}\n");
    exit(2);
}

$expected = [];
foreach (file($known, FILE_IGNORE_NEW_LINES) as $line) {
    $line = trim($line);
    if ($line !== '' && $line[0] !== '#') {
        $expected[] = strtolower($line);
    }
}
sort($expected);

$added = array_values(array_diff($current, $expected));
$removed = array_values(array_diff($expected, $current));

echo 'Laravel ', $version, ': ', count($current), ' directive methods (known: ', count($expected), ")\n";

if ($added === [] && $removed === []) {
    echo "No drift.\n";
    exit(0);
}

foreach ($added as $name) {
    echo "+ {$name}  (new in Laravel: add to markup_fmt/src/blade.rs and known-compile-methods.txt)\n";
}
foreach ($removed as $name) {
    echo "- {$name}  (gone from Laravel: review markup_fmt/src/blade.rs and known-compile-methods.txt)\n";
}
echo "\nDrift detected: review the Blade directive table, then update known-compile-methods.txt and its '# Laravel vX' header.\n";
exit(1);
